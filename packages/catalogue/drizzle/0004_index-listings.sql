CREATE TABLE "listings" (
	"id" integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY (sequence name "listings_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"type" "package_type" NOT NULL,
	"package_id" text NOT NULL,
	"title" text,
	"summary" text,
	"author_name" text,
	"author_username" text,
	"provider_id" text,
	"provider_name" text,
	"url" text,
	"marketplace_url" text,
	"tags" text[] DEFAULT '{}'::text[] NOT NULL,
	"systems" text[] DEFAULT '{}'::text[] NOT NULL,
	"premium" boolean DEFAULT false NOT NULL,
	"exclusive" boolean DEFAULT false NOT NULL,
	"status" text,
	"last_updated" timestamp with time zone,
	"latest_version" text,
	"versions" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"hash" text NOT NULL,
	"delisted_at" timestamp with time zone,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "listings_type_packageId_unique" UNIQUE("type","package_id")
);
