/**
 * The configuration both processes read from the environment: the server through `src/env.ts`, the worker through
 * {@link readConfig}. One schema for each variable, so that they cannot read it differently.
 */
import { z } from 'zod';

/** A PostgreSQL connection string. */
export const DatabaseUrl = z.url({ protocol: /^postgres(?:ql)?$/ });

/** The API keys accepted, separated by commas; at least one. */
export const ApiKeys = z
  .string()
  .transform(value =>
    value
      .split(',')
      .map(key => key.trim())
      .filter(key => key !== ''),
  )
  .pipe(z.array(z.string().min(1)).min(1, 'at least one API key is needed'));

export const LOG_LEVELS = ['debug', 'info', 'warn', 'error'] as const;

/** The lowest level logged. */
export const LogLevel = z.enum(LOG_LEVELS).default('info');
export type LogLevel = z.infer<typeof LogLevel>;

/** What the worker needs. */
export const WorkerConfig = z.object({
  DATABASE_URL: DatabaseUrl,
  LOG_LEVEL: LogLevel,
  /** Where the migrations generated by drizzle-kit are. */
  MIGRATIONS_DIR: z.string().min(1).default('drizzle'),
});
export type WorkerConfig = z.infer<typeof WorkerConfig>;

/**
 * Reads the worker's configuration.
 *
 * @param env - The environment, such as `process.env`
 * @returns The configuration
 * @throws {Error} Naming every variable that is missing or invalid
 */
export function readConfig(env: Readonly<Record<string, string | undefined>>): WorkerConfig {
  const read = WorkerConfig.safeParse(env);
  if (!read.success) throw new Error(`Invalid configuration:\n${z.prettifyError(read.error)}`);
  return read.data;
}
