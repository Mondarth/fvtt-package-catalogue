/**
 * The configuration both processes read from the environment: the server through `src/env.ts`, the worker through
 * {@link readConfig}. One schema for each variable, so that they cannot read it differently.
 */
import { FOUNDRY_PACKAGE_INDEX, FOUNDRY_RELEASE_NOTES } from '@mondarth/fvtt-resolver/sources';
import { z } from 'zod';

/** A PostgreSQL connection string. */
export const DatabaseUrl = z.url({ protocol: /^postgres(?:ql)?$/ });

/** The API keys accepted, separated by commas; at least one. */
export const ApiKeys = z
  .string()
  .transform(value =>
    value
      .split(',')
      .map(key => key.trim())
      .filter(key => key !== ''),
  )
  .pipe(z.array(z.string().min(1)).min(1, 'at least one API key is needed'));

export const LOG_LEVELS = ['debug', 'info', 'warn', 'error'] as const;

/** The lowest level logged. */
export const LogLevel = z.enum(LOG_LEVELS).default('info');
export type LogLevel = z.infer<typeof LogLevel>;

/** A secret that may be left out; compose gives one left unset in `.env` as empty, which is none. */
const Token = z.preprocess(value => (value === '' ? undefined : value), z.string().min(1).optional());

/** Signs the website's cookies and encrypts what sign-in providers give: long, random, and kept secret. */
export const AuthSecret = z.string().min(32, 'AUTH_SECRET must be at least 32 characters');

/** The website's address as visitors reach it, without a trailing slash; sign-in providers send them back to it. */
export const SiteUrl = z.url({ protocol: /^https?$/ }).transform(url => url.replace(/\/+$/, ''));

/** Text the environment may leave out; compose gives one left unset in `.env` as empty, which is none. */
const given = z
  .string()
  .optional()
  .transform(value => (value === '' ? undefined : value));

/** A sign-in provider's app id or secret, left out where the provider is not offered. */
export const ProviderCredential = given;

/** The stand-in sign-in provider's address, for the end-to-end tests alone. */
export const TestProviderUrl = given.pipe(z.url().optional());

/** A whole number above none, from the environment's text. */
const Count = z.coerce.number().int().positive();

/** What the worker needs. */
export const WorkerConfig = z.object({
  DATABASE_URL: DatabaseUrl,
  LOG_LEVEL: LogLevel,
  /** Where the migrations generated by drizzle-kit are. */
  MIGRATIONS_DIR: z.string().min(1).default('drizzle'),
  /** Raises GitHub's limit from 60 requests an hour to 5000. No scopes are needed. */
  GITHUB_TOKEN: Token,
  GITLAB_TOKEN: Token,
  /** The most HTTP requests one crawl may make: loading every release of a package costs one or more each. */
  CRAWL_MAX_REQUESTS: Count.default(5000),
  /** How long the worker waits when there is nothing to crawl. */
  CRAWL_POLL_SECONDS: Count.default(5),
  /** How often the worker checks the packages held for changes on Foundry VTT's index. */
  REFRESH_MINUTES: Count.default(60),
  /** How long a package the index does not list waits to be crawled again. */
  REFRESH_STALE_DAYS: Count.default(7),
  /**
   * The most packages crawled each hour to warm the catalogue: those Foundry VTT's index lists that no client has needed
   * yet. None turns warming off.
   */
  WARM_PER_HOUR: z.coerce.number().int().nonnegative().default(300),
  /**
   * How many answers the worker keeps in memory, such as manifests and Foundry VTT's index, letting go of the least
   * recently used first. Most are a few kilobytes; the index is several megabytes.
   */
  CACHE_ENTRIES: Count.default(5000),
  /** How long after its last check a package's own manifest is due another. */
  OWN_MANIFEST_CHECK_MINUTES: Count.default(60),
  /** How many packages the worker crawls at once. */
  CRAWL_CONCURRENCY: Count.default(4),
  /** The most requests made to any one host at once, across every crawl in hand. */
  CRAWL_PER_HOST: Count.default(4),
  /** The package overrides: what the catalogue is told of packages whose sources mislead it. */
  PACKAGE_OVERRIDES_FILE: z.string().min(1).default('overrides.json'),
  /** Foundry VTT's package index; another only to test against. */
  FOUNDRY_INDEX_URL: z.url().default(FOUNDRY_PACKAGE_INDEX),
  /** Foundry VTT's release notes, which list its builds; another only to test against. */
  FOUNDRY_RELEASES_URL: z.url().default(FOUNDRY_RELEASE_NOTES),
});
export type WorkerConfig = z.infer<typeof WorkerConfig>;

/**
 * Reads the worker's configuration.
 *
 * @param env - The environment, such as `process.env`
 * @returns The configuration
 * @throws {Error} Naming every variable that is missing or invalid
 */
export function readConfig(env: Readonly<Record<string, string | undefined>>): WorkerConfig {
  const read = WorkerConfig.safeParse(env);
  if (!read.success) throw new Error(`Invalid configuration:\n${z.prettifyError(read.error)}`);
  return read.data;
}
