import { readFileSync } from 'node:fs';

import { paraglideVitePlugin } from '@inlang/paraglide-js';
import adapter from '@sveltejs/adapter-node';
import { sveltekit } from '@sveltejs/kit/vite';
import { svelteTesting } from '@testing-library/svelte/vite';
import { defaultClientConditions, defaultServerConditions } from 'vite';
import { defineConfig } from 'vitest/config';

/** The export condition under which the workspace's packages give their TypeScript sources. */
export const SOURCE = '@mondarth/fvtt-package-catalogue/source';

const { version } = JSON.parse(readFileSync(new URL('package.json', import.meta.url), 'utf8')) as { version: string };

/** What the server and the worker are built with: the catalogue's version, which the release sets in package.json. */
export const DEFINE = { __CATALOGUE_VERSION__: JSON.stringify(version) };

export default defineConfig({
  plugins: [
    sveltekit({
      compilerOptions: {
        // Runes mode throughout, except in libraries. Can be removed in Svelte 6.
        runes: ({ filename }) => (filename.split(/[/\\]/).includes('node_modules') ? undefined : true),
      },
      // Everything not in `dependencies` is bundled, so the image needs no node_modules: keep runtime libraries in
      // devDependencies.
      adapter: adapter(),
    }),
    // Compiles the website's messages into src/lib/paraglide, as project.inlang/paraglide.config.ts says.
    paraglideVitePlugin({ project: './project.inlang' }),
  ],
  // The workspace's packages are read from their sources, so a change to the contract needs no build to be seen here.
  // Setting conditions replaces Vite's, so they are given too.
  resolve: { conditions: [SOURCE, ...defaultClientConditions] },
  ssr: { resolve: { conditions: [SOURCE, ...defaultServerConditions] } },
  // The release sets the version in package.json before it builds (release.config.js).
  define: DEFINE,
  test: {
    expect: { requireAssertions: true },
    coverage: {
      provider: 'v8',
      include: ['src/**/*.{ts,svelte}'],
      exclude: [
        '**/*.d.ts',
        // Generated by paraglide from messages/.
        'src/lib/paraglide/**',
        // Wiring: the environment, the process and the connection to the database, covered by the E2E tests.
        'src/env.ts',
        'src/hooks.server.ts',
        'src/lib/server/runtime.ts',
        'src/lib/server/db/connect.ts',
        // Declarations, read by drizzle-kit; the migrations and the store's tests cover what they mean.
        'src/lib/server/db/schema.ts',
        'src/worker/main.ts',
      ],
      // lcov feeds Codecov, with paths from the repository root; json-summary feeds the CI job summary.
      reporter: ['text', 'html', ['lcov', { projectRoot: '../..' }], 'json-summary'],
      // Ratchet these upward as coverage improves; never lower them to make a change pass. Branches are counted apart
      // for components: Svelte compiles each `{expression}` in markup to `expression ?? ''`, a branch no string can
      // take, so a component's branch coverage says little. Its behaviour is in its tests.
      thresholds: {
        statements: 100,
        functions: 100,
        lines: 100,
        'src/**/*.ts': { statements: 100, branches: 100, functions: 100, lines: 100 },
        'src/**/*.svelte': { statements: 100, branches: 50, functions: 100, lines: 100 },
      },
    },
    projects: [
      {
        extends: true,
        test: {
          name: 'server',
          environment: 'node',
          include: ['tests/unit/**/*.test.ts'],
          exclude: ['tests/unit/**/*.svelte.test.ts'],
        },
      },
      {
        extends: true,
        plugins: [svelteTesting()],
        test: {
          name: 'ui',
          environment: 'happy-dom',
          include: ['tests/unit/**/*.svelte.test.ts'],
          setupFiles: ['tests/unit/setup-dom.ts'],
        },
      },
    ],
  },
});
