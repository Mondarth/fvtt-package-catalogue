import { execFileSync } from 'node:child_process';
import { describe, expect, it } from 'vitest';

/**
 * Regression: `.gitignore` had `releases/`, meant for semantic-release's artefacts, which also matched the route
 * directory `src/routes/api/v1/packages/[type=packageType]/[id]/releases/`. The endpoint was never committed: the tests
 * passed where it existed, and CI, which checks out only what is committed, could not find it.
 */
describe('.gitignore', () => {
  it('ignores no source, test, message or migration of a package, only what is generated', () => {
    const ignored = execFileSync(
      'git',
      [
        'ls-files',
        '--others',
        '--ignored',
        '--exclude-standard',
        '--',
        ...['src', 'tests', 'messages', 'drizzle'].map(dir => `:(glob)packages/*/${dir}/**`),
      ],
      { encoding: 'utf8' },
    )
      .split('\n')
      .filter(path => path !== '')
      // Generated by paraglide from the messages.
      .filter(path => !/^packages\/[^/]+\/src\/lib\/paraglide\//.test(path))
      // Written by the end-to-end tests.
      .filter(path => !/^packages\/[^/]+\/tests\/e2e\/(?:playwright-report|test-results)\//.test(path));
    expect(ignored).toEqual([]);
  });

  it.each(['releases/module-v1.0.0.zip', 'packages/catalogue/releases/x.zip'])(
    'still ignores the release artefact %s',
    path => {
      expect(() => execFileSync('git', ['check-ignore', '--no-index', '-q', path])).not.toThrow();
    },
  );
});
