import { paraglideVitePlugin } from '@inlang/paraglide-js';
import adapter from '@sveltejs/adapter-node';
import { sveltekit } from '@sveltejs/kit/vite';
import { svelteTesting } from '@testing-library/svelte/vite';
import { defineConfig } from 'vitest/config';

import { devPatreonProvider } from './src/lib/server/accounts/dev-patreon.js';
import { devProvider } from './src/lib/server/accounts/dev-provider.js';

import type { Plugin } from 'vite';

/**
 * A stand-in sign-in provider, with made-up users to sign in as, and a stand-in Patreon, on the development server
 * alone (`pnpm dev`): served before SvelteKit, at `/__dev/provider` and `/__dev/patreon`, which the server offers in
 * development (runtime.ts).
 */
const devSignIn: Plugin = {
  name: 'accounts:dev-sign-in',
  apply: 'serve',
  configureServer(server) {
    server.middlewares.use(devProvider());
    server.middlewares.use(devPatreonProvider());
  },
};

export default defineConfig({
  plugins: [
    devSignIn,
    sveltekit({
      compilerOptions: {
        // Runes mode throughout, except in libraries. Can be removed in Svelte 6.
        runes: ({ filename }) => (filename.split(/[/\\]/).includes('node_modules') ? undefined : true),
      },
      // Everything not in `dependencies` is bundled, so the image needs no node_modules: keep runtime libraries in
      // devDependencies.
      adapter: adapter(),
    }),
    // Compiles the website's messages into src/lib/paraglide, as project.inlang/paraglide.config.ts says.
    paraglideVitePlugin({ project: './project.inlang' }),
  ],
  // Beside the catalogue's development server, on 5173. Browsers share cookies between a host's ports, so that one
  // sign-in serves both, as one cookie on the parent domain does in production.
  server: { port: 5174, strictPort: true },
  test: {
    expect: { requireAssertions: true },
    coverage: {
      provider: 'v8',
      include: ['src/**/*.{ts,svelte}'],
      exclude: [
        '**/*.d.ts',
        // Generated by paraglide from messages/.
        'src/lib/paraglide/**',
        // Wiring: the environment, the process and the connection to the database, covered by the E2E tests.
        'src/env.ts',
        'src/hooks.server.ts',
        'src/migrate.ts',
        'src/lib/server/runtime.ts',
        'src/lib/server/db/connect.ts',
        // Declarations, read by drizzle-kit; the migrations and the stores' tests cover what they mean.
        'src/lib/server/db/schema.ts',
        'src/lib/server/accounts/schema.ts',
        'src/lib/server/subscriptions/schema.ts',
      ],
      // lcov feeds Codecov, with paths from the repository root; json-summary feeds the CI job summary.
      reporter: ['text', 'html', ['lcov', { projectRoot: '../..' }], 'json-summary'],
      // As in the catalogue: never lower these to make a change pass. Branches are counted apart for components, as
      // Svelte compiles each `{expression}` in markup to `expression ?? ''`, a branch no string can take.
      thresholds: {
        statements: 100,
        functions: 100,
        lines: 100,
        'src/**/*.ts': { statements: 100, branches: 100, functions: 100, lines: 100 },
        'src/**/*.svelte': { statements: 100, branches: 50, functions: 100, lines: 100 },
      },
    },
    projects: [
      {
        extends: true,
        test: {
          name: 'server',
          environment: 'node',
          include: ['tests/unit/**/*.test.ts'],
          exclude: ['tests/unit/**/*.svelte.test.ts'],
        },
      },
      {
        extends: true,
        plugins: [svelteTesting()],
        test: {
          name: 'ui',
          environment: 'happy-dom',
          include: ['tests/unit/**/*.svelte.test.ts'],
          setupFiles: ['tests/unit/setup-dom.ts'],
        },
      },
    ],
  },
});
